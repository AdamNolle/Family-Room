package com.familyroom.app

import org.json.JSONArray
import org.json.JSONObject
import java.util.UUID

data class FilmKeyframe(val time: Double, val value: Double) {
    fun json() = JSONObject().put("time", time).put("value", value)
}

data class FilmClip(
    val id: String = UUID.randomUUID().toString(), val assetId: String,
    val track: Int = 0, val start: Double = 0.0, val trimIn: Double = 0.0,
    val duration: Double = 3.0, val speed: Double = 1.0, val volume: Double = 1.0,
    val opacity: Double = 1.0, val exposure: Double = 0.0, val saturation: Double = 1.0,
    val title: String = "", val fadeIn: Double = 0.0, val fadeOut: Double = 0.0,
    val fadeInOffset: Double = 0.0, val fadeOutOffset: Double = 0.0,
    val opacityKeyframes: List<FilmKeyframe> = emptyList(), val volumeKeyframes: List<FilmKeyframe> = emptyList()
) {
    val end get() = start + duration / speed
    fun valueAt(time: Double, frames: List<FilmKeyframe>, fallback: Double): Double {
        val ordered = frames.sortedBy { it.time }
        if (ordered.isEmpty()) return fallback
        if (time <= ordered.first().time) return ordered.first().value
        for ((a, b) in ordered.zipWithNext()) if (time <= b.time) {
            return if (a.time == b.time) b.value else a.value + (b.value - a.value) * (time - a.time) / (b.time - a.time)
        }
        return ordered.last().value
    }
    fun fadeAt(outputTime: Double): Double {
        val entering = if (fadeIn > 0) ((outputTime + fadeInOffset) / fadeIn).coerceIn(0.0, 1.0) else 1.0
        val leaving = if (fadeOut > 0) ((duration / speed - outputTime + fadeOutOffset) / fadeOut).coerceIn(0.0, 1.0) else 1.0
        return entering * leaving
    }
    fun opacityAt(outputTime: Double) = (valueAt(outputTime * speed, opacityKeyframes, opacity) * fadeAt(outputTime)).coerceIn(0.0, 1.0)
    fun gainAt(outputTime: Double) = (valueAt(outputTime * speed, volumeKeyframes, volume) * fadeAt(outputTime)).coerceIn(0.0, 4.0)
    fun resized(to: Double): FilmClip {
        require(to.isFinite() && to in 0.001..86400.0)
        fun trim(frames: List<FilmKeyframe>): List<FilmKeyframe> {
            if (frames.isEmpty() || to >= duration) return frames
            val ordered = frames.sortedBy { it.time }
            val value = when {
                to <= ordered.first().time -> ordered.first().value
                to >= ordered.last().time -> ordered.last().value
                else -> ordered.zipWithNext().first { (a, b) -> to <= b.time }.let { (a, b) ->
                    if (a.time == b.time) b.value else a.value + (b.value - a.value) * (to - a.time) / (b.time - a.time)
                }
            }
            return ordered.filter { it.time < to } + FilmKeyframe(to, value)
        }
        return copy(duration = to, opacityKeyframes = trim(opacityKeyframes), volumeKeyframes = trim(volumeKeyframes))
    }
    fun json() = JSONObject().put("id", id).put("asset_id", assetId).put("track", track)
        .put("start", start).put("trim_in", trimIn).put("duration", duration).put("speed", speed)
        .put("volume", volume).put("opacity", opacity).put("exposure", exposure).put("saturation", saturation)
        .put("title", title).put("fade_in", fadeIn).put("fade_out", fadeOut)
        .put("fade_in_offset", fadeInOffset).put("fade_out_offset", fadeOutOffset)
        .put("opacity_keyframes", JSONArray(opacityKeyframes.map { it.json() }))
        .put("volume_keyframes", JSONArray(volumeKeyframes.map { it.json() }))

    companion object {
        fun from(value: JSONObject): FilmClip {
            fun frames(name: String) = value.rows(name).map { FilmKeyframe(it.getDouble("time"), it.getDouble("value")) }
            return FilmClip(value.getString("id"), value.getString("asset_id"), value.getInt("track"),
                value.getDouble("start"), value.getDouble("trim_in"), value.getDouble("duration"), value.getDouble("speed"),
                value.getDouble("volume"), value.getDouble("opacity"), value.getDouble("exposure"), value.getDouble("saturation"),
                value.getString("title"), value.getDouble("fade_in"), value.getDouble("fade_out"),
                value.optDouble("fade_in_offset", 0.0), value.optDouble("fade_out_offset", 0.0), frames("opacity_keyframes"), frames("volume_keyframes"))
        }
    }
}

data class FilmChapter(val title: String, val time: Double) {
    fun json() = JSONObject().put("title", title).put("time", time)
}

data class FilmProject(
    val id: String, val roomId: String, val title: String, val formatVersion: Int = 1,
    val versionId: String = "", val editor: String = "", val width: Int = 1920, val height: Int = 1080,
    val clips: List<FilmClip> = emptyList(), val chapters: List<FilmChapter> = emptyList(),
    val publishedAsset: String? = null, val createdAt: Long = System.currentTimeMillis() / 1000,
    val autoGenerated: Boolean = false, val privateDraft: Boolean = true
) {
    val duration get() = clips.maxOfOrNull { it.end } ?: 0.0
    val supportsEditing get() = formatVersion == 1
    fun json() = JSONObject().put("format_version", formatVersion).put("id", id).put("room_id", roomId)
        .put("title", title).put("version_id", versionId).put("editor", editor).put("width", width).put("height", height)
        .put("clips", JSONArray(clips.map { it.json() })).put("chapters", JSONArray(chapters.map { it.json() }))
        .put("published_asset", publishedAsset ?: JSONObject.NULL).put("created_at", createdAt)
        .put("auto_generated", autoGenerated).put("private_draft", privateDraft)

    companion object {
        fun from(value: JSONObject): FilmProject {
            require(value.optInt("format_version", 1) == 1) { "Update Family Room before editing this project format. The film has been preserved." }
            return FilmProject(value.getString("id"), value.getString("room_id"), value.getString("title"),
                value.optInt("format_version", 1), value.optString("version_id"), value.optString("editor"),
                value.getInt("width"), value.getInt("height"), value.rows("clips").map(FilmClip::from),
                value.rows("chapters").map { FilmChapter(it.getString("title"), it.getDouble("time")) },
                value.optString("published_asset").takeUnless { it.isEmpty() || it == "null" }, value.optLong("created_at"),
                value.optBoolean("auto_generated"), value.optBoolean("private_draft", !value.has("published_asset") || value.isNull("published_asset")))
        }
    }
}
