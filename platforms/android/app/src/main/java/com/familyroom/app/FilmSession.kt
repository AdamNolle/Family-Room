package com.familyroom.app

import android.content.Context
import android.media.MediaMetadataRetriever
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import org.json.JSONObject
import java.io.File

/** A native editing session backed by real, encrypted core draft revisions. */
class FilmSession(private val model: RoomModel, private val scope: CoroutineScope, private val context: Context) {
    var project by mutableStateOf<FilmProject?>(null); private set
    var selectedId by mutableStateOf<String?>(null); private set
    var saving by mutableStateOf(false); private set
    var preparing by mutableStateOf(false); private set
    var dirty by mutableStateOf(false); private set
    var error by mutableStateOf<String?>(null); private set
    var undoCount by mutableStateOf(0); private set
    var redoCount by mutableStateOf(0); private set
    var rendering by mutableStateOf(false); private set
    var renderStatus by mutableStateOf(""); private set
    var renderedFile by mutableStateOf<File?>(null); private set
    private var renderedProject: FilmProject? = null
    private var renderJob: Job? = null
    private val undo = ArrayDeque<FilmProject>()
    private val redo = ArrayDeque<FilmProject>()
    private var pendingSave: Job? = null
    private var generation = 0L
    private val writer = Mutex()
    val room get() = model.rooms.find { it.optString("id") == project?.roomId }
    val hasContributionPermission get() = room?.optString("role") in listOf("owner", "admin", "contributor")
    val canEdit get() = project?.supportsEditing == true && hasContributionPermission && !rendering
    val selected get() = project?.clips?.find { it.id == selectedId }

    fun clearError() { error = null }
    fun reportError(message: String) { error = message }
    fun select(id: String) { selectedId = id }
    fun create() {
        if (preparing || project != null) return
        val destination = model.roomId
        preparing = true
        scope.launch {
            try {
                val response = model.command(JSONObject().put("action", "create_story").put("room_id", destination))
                begin(FilmProject.from(response.getJSONObject("project")))
                model.reload()
            } catch (e: CancellationException) { throw e }
            catch (e: Exception) { model.status = e.message ?: "Cannot create a film." }
            finally { preparing = false }
        }
    }
    fun open(value: JSONObject) {
        try { begin(FilmProject.from(value).copy(privateDraft = true)) }
        catch (e: Exception) { model.status = e.message ?: "Cannot open this film." }
    }
    private fun begin(value: FilmProject) {
        clearMovie()
        pendingSave?.cancel(); generation++
        project = value; selectedId = value.clips.firstOrNull()?.id
        undo.clear(); redo.clear(); undoCount = 0; redoCount = 0; dirty = false; error = null
    }
    fun checkpoint() {
        project?.let { if (undo.lastOrNull() != it) undo.addLast(it) }
        while (undo.size > 100) undo.removeFirst()
        redo.clear(); counts()
    }
    private fun counts() { undoCount = undo.size; redoCount = redo.size }
    fun update(record: Boolean = true, transform: (FilmProject) -> FilmProject) {
        val previous = project ?: return
        if (!canEdit) { error = "Your Room role does not allow film edits."; return }
        val next = transform(previous)
        if (next == previous) return
        if (record) checkpoint()
        clearMovie()
        project = next.copy(privateDraft = true); generation++; dirty = true
        if (next.clips.none { it.id == selectedId }) selectedId = next.clips.firstOrNull()?.id
        pendingSave?.cancel()
        val revision = generation
        pendingSave = scope.launch { delay(1200); saveRevision(revision) }
    }
    fun modifyClip(id: String, record: Boolean = true, transform: (FilmClip) -> FilmClip) {
        update(record) { p -> p.copy(clips = p.clips.map { if (it.id == id) transform(it) else it }) }
    }
    fun undo() {
        if (!canEdit || undo.isEmpty()) return
        project?.let { redo.addLast(it) }
        val target = undo.removeLast()
        update(record = false) { target }; counts()
    }
    fun redo() {
        if (!canEdit || redo.isEmpty()) return
        project?.let { undo.addLast(it) }
        val target = redo.removeLast()
        update(record = false) { target }; counts()
    }
    fun save() {
        if (project?.autoGenerated == true) update { it.copy(autoGenerated = false) }
        pendingSave?.cancel()
        scope.launch { saveRevision(generation) }
    }
    fun close() {
        if (preparing || rendering) return
        pendingSave?.cancel()
        scope.launch {
            if (!dirty || saveRevision(generation)) {
                clearMovie(); project = null; selectedId = null; generation++
                model.reload()
            }
        }
    }
    private suspend fun saveRevision(revision: Long): Boolean = writer.withLock {
        val value = project ?: return@withLock true
        if (revision != generation) return@withLock false
        saving = true
        try {
            model.command(JSONObject().put("action", "save_story").put("project", value.json()))
            model.reload()
            if (generation == revision) dirty = false
            generation == revision
        } catch (e: CancellationException) { throw e }
        catch (e: Exception) { error = e.message ?: "Cannot save this draft."; false }
        finally { saving = false }
    }
    fun splitSelected() {
        val before = project ?: return
        val clip = selected ?: return
        if (!canEdit || preparing) return
        preparing = true
        scope.launch {
            try {
                val response = model.command(JSONObject().put("action", "split_story_clip").put("project", before.json())
                    .put("clip_id", clip.id).put("source_time", clip.duration / 2))
                if (project != before) error = "The draft changed while splitting. Try the split again."
                else update { FilmProject.from(response.getJSONObject("project")) }
            } catch (e: CancellationException) { throw e }
            catch (e: Exception) { error = e.message ?: "Cannot split this clip." }
            finally { preparing = false }
        }
    }
    private fun clearMovie() {
        renderedFile?.delete(); renderedFile = null; renderedProject = null; renderStatus = ""
    }
    fun cancelRender() { renderJob?.cancel() }
    fun render() {
        val value = project ?: return
        val assets = room?.rows("assets").orEmpty()
        if (!canEdit || preparing || value.clips.isEmpty()) return
        rendering = true; renderStatus = "Preparing originals…"
        renderJob = scope.launch {
            val sources = mutableMapOf<String, File>()
            val output = File(context.cacheDir, "rendered-film-${java.util.UUID.randomUUID()}.mp4")
            try {
                for ((index, assetId) in value.clips.map { it.assetId }.distinct().withIndex()) {
                    renderStatus = "Preparing original ${index + 1} of ${value.clips.map { it.assetId }.distinct().size}…"
                    val asset = assets.firstOrNull { it.optString("id") == assetId } ?: error("This original is no longer in the Room.")
                    val suffix = asset.optString("filename").substringAfterLast('.', "original").takeIf { it.matches(Regex("[A-Za-z0-9]{1,8}")) } ?: "original"
                    val original = withContext(Dispatchers.IO) { File.createTempFile("film-input-", ".$suffix", context.cacheDir) }
                    sources[assetId] = original
                    if (!asset.optBoolean("local")) model.command(JSONObject().put("action", "fetch").put("room_id", value.roomId).put("asset_id", assetId))
                    model.command(JSONObject().put("action", "materialize").put("room_id", value.roomId).put("asset_id", assetId).put("destination", original.absolutePath))
                }
                renderStatus = "Rendering movie on this device…"
                FilmRenderer.render(context, value, assets, sources, output)
                if (project != value) { output.delete(); error = "The draft changed while rendering. Render the latest version again." }
                else { clearMovie(); renderedProject = value; renderedFile = output; renderStatus = "Movie ready on this device" }
            } catch (e: CancellationException) { output.delete(); throw e }
            catch (e: Exception) { output.delete(); error = e.message ?: "This device could not render the movie. Your draft and originals are preserved." }
            finally { sources.values.forEach(File::delete); rendering = false; if (renderedFile == null) renderStatus = "" }
        }
    }
    fun publishMovie() {
        val before = project ?: return
        val file = renderedFile ?: return
        if (!canEdit || preparing || saving || renderedProject != before) return
        preparing = true
        pendingSave?.cancel()
        scope.launch {
            try {
                val movie = model.command(JSONObject().put("action", "import").put("room_id", before.roomId).put("path", file.absolutePath))
                val published = before.copy(publishedAsset = movie.getString("id"), privateDraft = false, autoGenerated = false)
                model.command(JSONObject().put("action", "save_story").put("project", published.json()).put("publish", true))
                project = published; renderedProject = published; generation++; dirty = false
                model.reload()
                model.sync(before.roomId)
            } catch (e: CancellationException) { throw e }
            catch (e: Exception) { error = e.message ?: "The movie could not be published. Your draft is preserved." }
            finally { preparing = false }
        }
    }
    fun dispose() { renderJob?.cancel(); pendingSave?.cancel(); clearMovie() }
    fun add(asset: JSONObject) {
        val before = project ?: return
        if (!canEdit || preparing) return
        preparing = true
        scope.launch {
            try {
                val kind = asset.optString("kind")
                val duration = if (kind == "photo") 3.0 else withContext(Dispatchers.IO) {
                    val file = File.createTempFile("film-source-", ".original", context.cacheDir)
                    try {
                        if (!asset.optBoolean("local")) model.command(JSONObject().put("action", "fetch").put("room_id", before.roomId).put("asset_id", asset.getString("id")))
                        model.command(JSONObject().put("action", "materialize").put("room_id", before.roomId).put("asset_id", asset.getString("id")).put("destination", file.absolutePath))
                        val retriever = MediaMetadataRetriever()
                        try {
                            retriever.setDataSource(file.absolutePath)
                            val seconds = (retriever.extractMetadata(MediaMetadataRetriever.METADATA_KEY_DURATION)?.toDoubleOrNull() ?: error("This original’s duration cannot be read.")) / 1000
                            require(seconds.isFinite() && seconds > 0) { "This original has no playable duration." }
                            if (kind == "audio") seconds else minOf(3.0, seconds)
                        } finally { retriever.release() }
                    } finally { file.delete() }
                }
                if (project != before) { error = "The draft changed while preparing the original. Add it again."; return@launch }
                val layer = if (kind == "audio") 1 else 0
                val start = before.clips.filter { it.track == layer }.maxOfOrNull { it.end } ?: 0.0
                require(start + duration <= 86400) { "This original exceeds the film’s 24-hour timeline limit. Trim it before adding." }
                val clip = FilmClip(assetId = asset.getString("id"), track = layer, start = start, duration = duration)
                update { it.copy(clips = it.clips + clip) }; selectedId = clip.id
            } catch (e: CancellationException) { throw e }
            catch (e: Exception) { error = e.message ?: "Cannot add this original." }
            finally { preparing = false }
        }
    }
}
