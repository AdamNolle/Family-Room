package com.familyroom.app

import org.json.JSONObject
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.launch
import java.util.UUID

internal data class WeeklyReelSelection(
 val project: FilmProject,
 val alreadySaved: Boolean,
)

internal data class WeeklyReelAssetCandidate(
 val id: String,
 val kind: String,
 val contributedAt: Long,
 val deleted: Boolean = false,
)

internal data class WeeklyReelStoryCandidate(
 val id: String,
 val createdAt: Long,
 val autoGenerated: Boolean,
 val privateDraft: Boolean,
 val published: Boolean = false,
 val archived: Boolean = false,
)

internal fun selectWeeklyReelAssets(
 assets: List<WeeklyReelAssetCandidate>,
 nowSeconds: Long,
): List<WeeklyReelAssetCandidate> {
 val start = nowSeconds - 7 * 86_400
 return assets.asSequence()
  .filter { !it.deleted && it.kind in setOf("photo", "video") }
  .filter { it.contributedAt in start..(nowSeconds + 300) }
  .sortedBy { it.contributedAt }
  .toList()
  .takeLast(20)
}

internal fun reusableWeeklyReelDraft(
 stories: List<WeeklyReelStoryCandidate>,
 nowSeconds: Long,
): WeeklyReelStoryCandidate? {
 val start = nowSeconds - 7 * 86_400
 return stories.asSequence()
  .filter { it.autoGenerated && it.privateDraft && !it.published && !it.archived }
  .filter { it.createdAt in start..(nowSeconds + 300) }
  .maxByOrNull { it.createdAt }
}

/** Build a private weekly reel from recently contributed Room media, reusing this week's draft. */
internal fun weeklyReelProject(room: JSONObject, nowSeconds: Long): WeeklyReelSelection? {
    val roomId = room.optString("id").takeIf(String::isNotBlank) ?: return null
    val title = "This week in ${room.optString("name", "your Room")}"
 val stories = room.rows("stories")
 val existingId = reusableWeeklyReelDraft(
  stories.map { story ->
   WeeklyReelStoryCandidate(
    id = story.optString("id"),
    createdAt = story.optLong("created_at"),
    autoGenerated = story.optBoolean("auto_generated"),
    privateDraft = story.optBoolean("private_draft"),
    published = !story.isNull("published_asset"),
    archived = story.optBoolean("archived"),
   )
  },
  nowSeconds,
 )?.id
 val existing = stories.firstOrNull { it.optString("id") == existingId }
    if (existing != null) {
        return runCatching { WeeklyReelSelection(FilmProject.from(existing), alreadySaved = true) }
            .getOrNull()
    }

 val assets = room.rows("assets")
 val assetsById = assets.associateBy { it.optString("id") }
 val recent = selectWeeklyReelAssets(
  assets.map { asset ->
   WeeklyReelAssetCandidate(
    id = asset.optString("id"),
    kind = asset.optString("kind"),
    contributedAt = asset.optLong("contributed_at"),
    deleted = asset.optBoolean("deleted"),
   )
  },
  nowSeconds,
 ).mapNotNull { assetsById[it.id] }
    if (recent.isEmpty()) return null

    val clips = recent.mapIndexed { index, asset ->
        FilmClip(
            assetId = asset.optString("id"),
            start = index * 3.0,
            duration = 3.0,
            fadeIn = 0.3,
            fadeOut = 0.3,
        )
    }
    return WeeklyReelSelection(
        FilmProject(
            id = UUID.randomUUID().toString(),
            roomId = roomId,
            title = title,
            clips = clips,
            createdAt = nowSeconds,
            autoGenerated = true,
        ),
        alreadySaved = false,
    )
}

internal fun openOrCreateWeeklyReel(
    model: RoomModel,
    room: JSONObject,
    scope: CoroutineScope,
    nowSeconds: Long = System.currentTimeMillis() / 1_000,
) {
    val selection = weeklyReelProject(room, nowSeconds)
    if (selection == null) {
        model.status = "Add photos or videos to this Room this week first."
        return
    }
    val project = selection.project
    if (selection.alreadySaved) {
        model.studio.open(project.json())
        return
    }
    scope.launch {
        if (model.execute(JSONObject().put("action", "save_story").put("project", project.json()))) {
            model.studio.open(project.json())
        }
    }
}
